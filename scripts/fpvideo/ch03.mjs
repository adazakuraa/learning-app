import { T, txt, box, list, tag, bars, vbars, flow, layers, person, versus, lines, st, scene, slide, write } from './lib.mjs';
const B = (t, c, y, o = {}) => box(t, { color: c, at: [80, y], ...o });
const comp = (r, n) => Array.from({ length: n + 1 }, (_, i) => Math.round(100 * (1 + r) ** i));
const simple = (r, n) => Array.from({ length: n + 1 }, (_, i) => Math.round(100 * (1 + r * i)));

write('FP03-01', '金利と複利', [
  slide(st('第3章、「金利・インフレ・お金の時間価値」です。お金が増えたり、目減りしたりする仕組みを学びます。', T('第3章　金利・インフレ・お金の時間価値'), list(['金利と複利', 'インフレとデフレ', 'お金の時間価値', '金利・為替と日銀の役割']))),
  scene(
    st('「金利と複利」です。利息のつき方には、単利と複利の2種類があります。', T('単利と複利')),
    st('単利は、最初に預けたお金、元本にだけ利息がつきます。複利は、ついた利息にも、さらに利息がつきます。', ...versus({ title: '単利', items: ['元本にだけ利息がつく', '毎年同じ額ずつ増える'], color: 'blue' }, { title: '複利', items: ['利息にも利息がつく', '雪だるま式に増える'], color: 'green' })),
  ),
  scene(
    st('100万円を年5パーセントで運用した場合を、グラフで比べてみましょう。10年ではあまり差がありませんが、30年たつと、単利は250万円、複利はおよそ432万円。大きな差になります。', T('時間がたつほど差が開く'), lines([[simple(0.05, 30).filter((_, i) => i % 5 === 0), 'blue', '単利 250万'], [comp(0.05, 30).filter((_, i) => i % 5 === 0), 'green', '複利 約432万']], ['0年', '5', '10', '15', '20', '25', '30年'], { max: 450 }), { ex: true }),
    st('複利を味方にするコツは、早く始めて、長く続けることです。', B('複利のコツ：**早く始めて、長く続ける**', 'yellow', 610)),
  ),
  scene(
    st('ここで便利なのが、72の法則です。72を、年の利率で割ると、お金がおよそ2倍になる年数がわかります。', T('72の法則'), B('**72 ÷ 年利（%）≒ 2倍になる年数**', 'yellow', 160)),
    st('年3パーセントなら24年、6パーセントなら12年で2倍です。', bars([['年1%', 72, 'gray', '約72年'], ['年3%', 24, 'blue', '約24年'], ['年6%', 12, 'green', '約12年']], { at: [80, 270], max: 80 })),
    st('ただし、複利は借金にも働きます。年15パーセントのリボ払いなら、およそ5年で、借金が2倍になる計算です。', B('借金にも複利：年15%なら **約5年で借金が2倍**', 'pink', 520), { ex: true }),
  ),
]);

