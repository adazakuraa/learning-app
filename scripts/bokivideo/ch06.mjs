write('BK06-02', '減価償却（定額法・間接法）', [
  scene(
    st('120万円のトラックを買って、6年間使うとします。もし買った年に、全部を費用にしたらどうなるでしょう。', T('減価償却とは')),
    st('その年だけ大赤字で、残りの5年は費用ゼロになってしまいます。でも実際は、トラックは6年間ずっと商売の役に立っています。', vbars([['1年目', 120, 'pink', '120万'], ['2年目', 0.5, 'gray', '0'], ['3年目', 0.5, 'gray', '0'], ['4年目', 0.5, 'gray', '0'], ['5年目', 0.5, 'gray', '0'], ['6年目', 0.5, 'gray', '0']], { at: [140, 200], h: 340, id: 'bad' }), { ex: true }),
    st('そこで、使う期間に分けて、少しずつ費用にします。これが減価償却です。こうすると、毎年のもうけを正しく計算できます。', vbars([['1年目', 20, 'purple', '20万'], ['2年目', 20, 'purple', '20万'], ['3年目', 20, 'purple', '20万'], ['4年目', 20, 'purple', '20万'], ['5年目', 20, 'purple', '20万'], ['6年目', 20, 'purple', '20万']], { at: [140, 200], h: 340, max: 120 }), { hide: ['bad'] }),
  ),
  scene(
    st('3級の計算方法は、定額法です。取得原価から残存価額を引いて、耐用年数でわります。毎年同じ金額になります。', T('定額法'), box('1年分 ＝（取得原価 − 残存価額）÷ 耐用年数', { color: 'yellow', at: [80, 160] })),
    st('残存価額は、使い終わったときに残る価値です。トラックの例では、残存価額ゼロ、耐用年数6年なら、120万わる6で、1年20万円です。', box('（120万 − 0）÷ 6年 ＝ **20万円**', { color: 'green', at: [80, 300] })),
  ),
  scene(
    st('記帳の方法は、間接法です。トラックの金額は減らさずに、減価償却累計額という科目を、右側に積み上げていきます。', T('間接法'), jr([['減価償却費', 200000, '車両運搬具減価償却累計額', 200000]], { at: [90, 150] })),
    st('2年たつと、累計額は40万円。帳簿上の価値は、120万ひく40万で、80万円です。いくらで買って、どれだけ古くなったかが、両方わかるのが間接法の良いところです。', tacc([{ name: '車両運搬具', c: 'blue', l: ['取得 1,200,000'], r: [] }, { name: '減価償却累計額', c: 'pink', l: [], r: ['1年目 200,000', '2年目 200,000'] }], { at: [80, 320] })),
  ),
  scene(
    st('期の途中で買ったときは、使った月数分だけにします。12月1日に、60万円の備品を買いました。耐用年数5年、決算日は3月31日です。', T('期中に買ったとき'), tbar([['使った4か月', 4, 'purple'], ['来期以降', 8, 'gray']], [[0, '12月1日'], [4 / 12, '3月31日 決算']], { at: [90, 160] })),
    st('1年分は12万円。使ったのは12月から3月の4か月なので、12万かける12分の4で、4万円です。買った月も1か月に数えます。そして、土地は価値が減らないので、減価償却しません。', box('60万 ÷ 5年 × 4/12 ＝ **4万円**\n**買った月も数える**／**土地は償却しない**', { color: 'yellow', at: [80, 420] })),
  ),
]);

